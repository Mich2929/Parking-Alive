/**
 * Normalizes an LTA CarParkAvailabilityv2 raw item into a full Carpark object
 */
export function convertLtaItemToCarpark(item: any, index: number = 0): Carpark {
  let lat = 1.29375;
  let lng = 103.85718;
  if (item.Location && typeof item.Location === 'string') {
    const parts = item.Location.trim().split(/\s+/);
    if (parts.length >= 2) {
      lat = parseFloat(parts[0]) || lat;
      lng = parseFloat(parts[1]) || lng;
    }
  }

  const agency: AgencyType = (item.Agency as AgencyType) || 'LTA';
  const avail = typeof item.AvailableLots === 'number' ? item.AvailableLots : 50;
  const estimatedTotal = Math.max(avail + Math.floor(avail * 0.4), 100);

  return {
    id: `lta-${item.CarParkID || index}`,
    code: item.CarParkID ? `LTA-${item.CarParkID}` : `CP-${index + 1}`,
    name: item.Development || `Carpark ${item.CarParkID || index}`,
    address: `${item.Development || 'Location'}, ${item.Area || 'Singapore'}`,
    postalCode: '000000',
    agency,
    type: agency === 'HDB' ? 'HDB MULTI-STOREY' : agency === 'URA' ? 'URA OFF-STREET' : 'COMMERCIAL / MALL',
    distanceMeters: 150 + index * 80,
    walkMinutes: 2 + Math.floor(index * 1.2),
    driveMinutes: 1 + Math.floor(index * 0.5),
    totalLots: estimatedTotal,
    availableLots: avail,
    carLots: item.LotType === 'C' ? avail : Math.floor(avail * 0.8),
    motorLots: item.LotType === 'Y' ? avail : Math.floor(avail * 0.1),
    heavyLots: item.LotType === 'H' ? avail : 0,
    rateDescription: agency === 'HDB' ? '$0.60 / 30 mins (HDB EPS)' : '$2.40 for 1st hr, $1.20 / sub 30m',
    shortRate: agency === 'HDB' ? '$0.60/30m' : '$1.20/30m',
    hasEv: index % 2 === 0,
    evChargingInfo: index % 2 === 0 ? 'SP Mobility & Fast DC Chargers Available' : undefined,
    evChargerCount: index % 2 === 0 ? 2 : 0,
    hasFreeSunPh: agency === 'HDB',
    freeParkingInfo: agency === 'HDB' ? 'Free Parking Sunday & PH (7am – 10:30pm)' : undefined,
    erpGantryFee: item.Area === 'Marina' || item.Area === 'CBD' ? 2.0 : 0.0,
    gracePeriodMinutes: 10,
    coordinates: {
      lat,
      lng,
      mapX: 40 + (index % 5) * 6,
      mapY: 42 + (index % 4) * 6,
    },
  };
}

